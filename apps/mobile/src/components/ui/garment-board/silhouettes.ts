// ADR 0025's vocabulary as Phase 6 colour fashion flats (style A, "ink edge"): 33 drawings,
// the eight approved additions (the `x-` ids) and the six category glyphs, all on one 64 x 64
// viewBox. A drawing is a list of groups painted in order. Each group's `outline` is filled
// with one colour role and stroked with the ink edge; its `parts` are clipped to that
// outline, so shading and seams never spill past the edge. `garment-painting.tsx` paints
// them and owns the level-of-detail rule.
//
// Part kinds: `fs` shade, `fl` light, `fk` dark trim, `fa` material, `fas` material shade,
// `fm` main (a panel over another group), `fh` hardware; lines: `D` construction (ink, or the
// tone colour where ink sits under 3:1 on the fill), `Dh` zip in the hardware colour, `T` tone
// line, `Ta` tone line on the material, `S` stitch, `Sh` stitch in the hardware colour, `Sa`
// stitch on the material.
//
// Bounds are measured from the outlines, stroke excluded, and are what ADR 0025's composition
// rule reads; silhouettes.test.mjs recomputes them from the outlines.
export type SilhouetteFillRole = 'main' | 'shade' | 'toneLine' | 'darkTrim' | 'material' | 'hardware';
export type SilhouettePartKind =
  | 'fs' | 'fl' | 'fk' | 'fa' | 'fas' | 'fm' | 'fh'
  | 'D' | 'Dh' | 'T' | 'Ta' | 'S' | 'Sh' | 'Sa';

export type SilhouetteGroup = Readonly<{
  outline: string;
  fill: SilhouetteFillRole;
  parts: readonly (readonly [SilhouettePartKind, string])[];
  /** A group drawn without the ink edge (the scarf's fringe). */
  stroked?: false;
}>;

